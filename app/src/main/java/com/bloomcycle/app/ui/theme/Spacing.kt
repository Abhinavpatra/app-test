package com.bloomcycle.app.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * One spacing scale for the whole app. Cards, screens and charts all snap to these so
 * rhythm stays consistent even when a layout is built quickly.
 */
object Spacing {
    val xxxs: Dp = 2.dp
    val xxs: Dp = 4.dp
    val xs: Dp = 8.dp
    val sm: Dp = 12.dp
    val md: Dp = 16.dp
    val lg: Dp = 24.dp
    val xl: Dp = 32.dp
    val xxl: Dp = 44.dp
    val screen: Dp = 20.dp

    /** Comfortable reading measure for article copy. */
    val measure: Dp = 34.dp
}
